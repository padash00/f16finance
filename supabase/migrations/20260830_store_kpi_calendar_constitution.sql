-- ─────────────────────────────────────────────────────────────────────────
-- Календарь модуля: убрать День Конституции с 30 августа.
-- ─────────────────────────────────────────────────────────────────────────
-- Миграция 20260828 поправила таблицу kz_holidays, из которой праздники брал
-- общий календарь портала. Но в календарь модуля эффективности праздники
-- успели импортироваться раньше — со старой датой. Там они и остались:
-- 30 августа 2026 и 2027 значатся Днём Конституции, хотя законом от
-- 01.07.2026 праздник перенесён на 15 марта.
--
-- Удаляем только импортированные строки. Если владелец завёл этот день сам
-- (source = 'manual'), это его решение, и трогать его нельзя.

delete from public.store_kpi_calendar_days
where day in ('2026-08-30', '2027-08-30')
  and name ilike '%конституц%'
  and source is distinct from 'manual';
