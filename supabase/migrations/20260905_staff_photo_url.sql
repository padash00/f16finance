-- ─────────────────────────────────────────────────────────────────────────
-- Аватар сотрудника: колонка, которую код считал существующей.
-- ─────────────────────────────────────────────────────────────────────────
-- В логах базы копятся ошибки «column staff_1.photo_url does not exist».
-- Причина простая: код в двух местах уверен, что у сотрудника есть аватар,
-- а колонки в таблице нет.
--
--   app/api/me/avatar/route.ts — загрузка аватара пишет staff.photo_url и
--   падает с ошибкой. Оператор аватар поставить может (у него отдельная
--   таблица operator_profiles), а сотрудник админ-состава — нет.
--
--   app/api/team-chat/route.ts — чтение аватаров для чата. Здесь ошибка
--   проглатывается: запрос просто ничего не возвращает, и в чате у
--   сотрудников не появляется фото. Молча и без единого признака поломки.
--
-- Таблица staff старше папки миграций и заводилась вручную, поэтому колонку
-- просто забыли. Заводим её здесь — рядом с operator_profiles.photo_url,
-- чтобы у обеих половин команды аватар хранился одинаково.

alter table public.staff
  add column if not exists photo_url text null;

comment on column public.staff.photo_url is
  'Ссылка на аватар сотрудника. Парная к operator_profiles.photo_url.';
