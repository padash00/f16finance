-- Взято не из общих соображений, а из pg_stat_statements боевой базы:
-- советник индексов Supabase назвал их прямым текстом, а замеры показали,
-- сколько это стоит.
--
--   point_sales по sold_at        — 25 551 вызов, СРЕДНЕЕ 95,8 мс, 7,6% всего
--                                   времени базы. Самый медленный прикладной
--                                   запрос в системе. Оценка плана падает с
--                                   41466 до 8286 — впятеро.
--   inventory_balances по updated_at — 287 952 вызова, 2,4 мс.
--   inventory_balances по location_id — 131 234 вызова, 2,8 мс.
--
-- Обе выборки point_sales сортируют по sold_at DESC и берут страницу. Без
-- индекса это значит прочитать всю таблицу продаж и отсортировать её целиком —
-- каждый раз, тридцать тысяч раз за период.

-- ── ПОЧЕМУ БЕЗ CONCURRENTLY ───────────────────────────────────────────────
-- Напрашивается CREATE INDEX CONCURRENTLY: он строится без блокировки записи.
-- Но SQL Editor в Supabase оборачивает даже одиночный запрос в транзакцию, а
-- CONCURRENTLY внутри транзакции запрещён — отсюда ошибка 25001.
--
-- Поэтому обычный CREATE INDEX. Он берёт блокировку на запись в таблицу на
-- время построения: читать можно, писать — нет. Для таблиц такого размера это
-- секунды, но секунды, в которые касса не сможет провести продажу.
--
-- ЗАПУСКАТЬ В ЗАТИШЬЕ — утром до открытия или в перерыве, не в вечерний пик.

-- ── ШАГ 0: понять цену блокировки ─────────────────────────────────────────
-- Сначала посмотреть, насколько таблицы велики. Сотни тысяч строк — это
-- секунда-две; миллионы — стоит дождаться закрытия.
--
-- select relname,
--        n_live_tup as строк,
--        pg_size_pretty(pg_total_relation_size(relid)) as размер
--   from pg_stat_user_tables
--  where relname in ('point_sales', 'inventory_balances');

-- ── ШАГ 1: индексы ────────────────────────────────────────────────────────

create index if not exists idx_point_sales_sold_at
  on public.point_sales (sold_at desc);

create index if not exists idx_inventory_balances_updated_at
  on public.inventory_balances (updated_at desc);

create index if not exists idx_inventory_balances_location
  on public.inventory_balances (location_id);

