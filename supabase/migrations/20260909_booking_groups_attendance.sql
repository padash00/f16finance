-- ─────────────────────────────────────────────────────────────────────────
-- Бронь компанией: одна запись вместо пяти.
-- ─────────────────────────────────────────────────────────────────────────
-- Эта миграция про то, чтобы заменить тетрадь, а не про красоту модели.
--
-- В тетради компания на пять мест была ОДНОЙ записью: имя, телефон, номера
-- ПК, время. Если в системе это будет пять отдельных броней без связи,
-- оператор потеряет главное — что это один человек и один разговор. Позвонит
-- отменять, а искать придётся пять строк.
--
-- Поэтому вводится группа. Строк по-прежнему пять, по одной на станцию: иначе
-- не проверить пересечения и не отменить один ПК из пяти. Но у них общий
-- признак, и в списке они показываются как одна бронь.

alter table public.client_bookings
  add column if not exists booking_group_id uuid null;

comment on column public.client_bookings.booking_group_id is
  'Одна бронь на несколько ПК: компания пришла вместе. NULL — бронь на один компьютер.';

-- Собрать всю группу по одному участнику — основной запрос при отмене и при
-- показе списка.
create index if not exists idx_client_bookings_group
  on public.client_bookings (booking_group_id)
  where booking_group_id is not null;

-- ── Почему здесь НЕТ отметки явки ─────────────────────────────────────────
-- Напрашивалось добавить галочку «пришёл» — она есть в любой системе броней.
-- Но в тетради её не ставили, и это решающий довод: функция, которую никто не
-- заполняет, хуже её отсутствия. В базе появляются пустые поля, которые
-- выглядят как данные, и построенная на них статистика неявок врёт.
--
-- При этом сам вопрос «пришёл ли человек» остаётся полезным. Ответить на него
-- можно будет без участия оператора: слой наблюдения за станциями знает,
-- была ли машина занята в забронированное время. Тогда явка вычисляется из
-- факта, а не из того, вспомнил ли кто-то нажать кнопку.
--
-- Возвращаться к этому имеет смысл, когда агент будет стоять на всех машинах.

