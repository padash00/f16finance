-- Отметка «сегодня напоминали» на попытке экзамена.
--
-- Напоминание уходит раз в сутки: за сутки до срока и в день срока. Без
-- отметки крон слал бы его при каждом запуске — то есть каждый час, и человек
-- выключил бы уведомления вовсе, вместе с теми, что важны.
alter table public.operator_exam_attempts
  add column if not exists reminded_on date;

comment on column public.operator_exam_attempts.reminded_on is
  'Дата последнего напоминания о несданном экзамене (KZ). Защита от повторов.';
