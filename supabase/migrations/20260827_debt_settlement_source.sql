-- Чем закрыт долг: удержанием из зарплаты или деньгами мимо неё.
--
-- Долг вычитается из суммы к выплате (netAmount = начислено + премии − штрафы
-- − ДОЛГ − аванс), но расчёт недели брал из таблицы только строки со статусом
-- 'active'. Как только долг закрывался, он выпадал из формулы — и «к выплате»
-- вырастало ровно на его сумму. Выплаченная неделя оживала и показывала
-- остаток размером в долг: «Частично» вместо «Выплачено».
--
-- Пример с прода: начислено 44 000, долг 500, выдано 43 500 — ровно столько,
-- сколько причиталось. После закрытия долга к выплате стало 44 000, и неделя
-- показала остаток 500.
--
-- Различить два способа закрытия по status нельзя: и удержание из зарплаты,
-- и «клиент занёс деньги» пишут 'paid'. Отсюда колонка:
--
--   salary — удержано из зарплаты. Долг обязан вычитаться и после закрытия:
--            деньги уже удержаны, сумма к выплате меняться не должна.
--   cash   — занесли деньгами мимо зарплаты. Вычитаться перестаёт, и рост
--            суммы к выплате здесь правильный.
--   null   — закрыт до этой миграции, способ неизвестен. Ведёт себя как
--            раньше (в расчёт не попадает) — историю не трогаем.
alter table public.debts
  add column if not exists settled_via text null;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'debts_settled_via_check'
  ) then
    alter table public.debts
      add constraint debts_settled_via_check
      check (settled_via is null or settled_via in ('salary', 'cash'));
  end if;
end $$;

-- Расчёт недели спрашивает долги по паре «оператор + неделя» и теперь смотрит
-- ещё и на способ закрытия.
create index if not exists debts_operator_week_settled_idx
  on public.debts (operator_id, week_start, settled_via);

comment on column public.debts.settled_via is
  'Чем закрыт долг: salary — удержан из зарплаты (продолжает вычитаться), cash — занесён деньгами мимо зарплаты, null — закрыт до 2026-08-27, способ неизвестен';
