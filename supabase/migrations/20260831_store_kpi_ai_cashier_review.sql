-- ─────────────────────────────────────────────────────────────────────────
-- Журнал запусков ИИ: добавляем разбор по продавцу.
-- ─────────────────────────────────────────────────────────────────────────
-- Появился третий вид разбора: не смена и не месяц, а один человек за период.
-- Он отвечает на вопрос, которого не было ни у смены, ни у месяца, — как
-- построить разговор именно с этим продавцом.
--
-- Тип запуска ограничен списком намеренно: журнал должен уметь ответить,
-- что именно модель видела и что ответила, а свободная строка в этом поле
-- через полгода превращается в свалку опечаток.

alter table public.store_kpi_ai_runs
  drop constraint if exists store_kpi_ai_runs_task_type_check;

alter table public.store_kpi_ai_runs
  add constraint store_kpi_ai_runs_task_type_check
  check (task_type in (
    'POST_SHIFT_CASHIER_REVIEW',
    'MONTHLY_DEMAND_REVIEW',
    'DAILY_SHIFT_FORECAST',
    'CASHIER_PERIOD_REVIEW'
  ));
