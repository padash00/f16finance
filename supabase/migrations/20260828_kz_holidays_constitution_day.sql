-- ─────────────────────────────────────────────────────────────────────────
-- Праздники РК: День Конституции переехал, переносы выходных добавлены.
-- ─────────────────────────────────────────────────────────────────────────
-- Таблица kz_holidays сидировалась в мае и с тех пор устарела.
--
-- 1. День Конституции. Законом, вступившим в силу 01.07.2026, праздник
--    перенесён с 30 августа на 15 марта. В таблице до сих пор стоит
--    30 августа — и на 2026, и на 2027 год. Календарь на портале показывает
--    команде нерабочий день, которого нет.
--
-- 2. Переносы выходных. Когда праздник выпадает на выходной, отдых
--    переносится на ближайший рабочий день. В таблице их не было вовсе,
--    хотя для планирования смен они важнее самого праздника.
--
-- Источник дат — справочник lib/data/kz-calendar.ts, он же используется
-- модулем эффективности продавцов. Здесь правится только общий календарь
-- портала: модуль читает справочник напрямую и в этой таблице не нуждается.

-- 30 августа больше не праздник ни в одном году.
delete from public.kz_holidays where date in ('2026-08-30', '2027-08-30');

-- 15 марта 2027 — первый День Конституции на новой дате.
-- В 2026-м его нет: 15 марта прошло до вступления закона в силу, а 30 августа
-- уже после.
insert into public.kz_holidays (date, name, is_workday_off, description) values
  ('2027-03-15', 'День Конституции', true, 'С 2026 года праздник перенесён с 30 августа')
on conflict (date) do update
  set name = excluded.name,
      is_workday_off = excluded.is_workday_off,
      description = excluded.description;

-- Переносы выходных: праздник выпал на субботу или воскресенье, отдых сдвинут.
insert into public.kz_holidays (date, name, is_workday_off, description) values
  ('2026-10-26', 'Перенос выходного',  true, 'За День Республики Казахстан'),
  ('2027-01-04', 'Перенос выходного',  true, 'За новогодние праздники'),
  ('2027-03-24', 'Перенос выходного',  true, 'За Наурыз мейрамы'),
  ('2027-05-03', 'Перенос выходного',  true, 'За Праздник единства народа Казахстана'),
  ('2027-05-10', 'Перенос выходного',  true, 'За День Победы')
on conflict (date) do nothing;
