-- ─────────────────────────────────────────────────────────────────────────
-- Погода по часам: смена дневная и смена ночная живут в разной погоде.
-- ─────────────────────────────────────────────────────────────────────────
-- До сих пор хранился только день целиком: максимум температуры и сумма
-- осадков за сутки. Для магазина, где работают две смены, этого мало.
--
-- Пример. 12 июля днём +33, вечером гроза, к 21:00 +19 и сухо. По дневным
-- данным обе смены получают «жара» и «дождь». Дневная — верно, ночная —
-- нет: её кассир работал в тёплый сухой вечер. Модуль подмешал бы шум ровно
-- туда, где мы пытаемся его убрать: в разделение «слабый поток» и «слабая
-- работа».
--
-- Почасовой ряд хранится компактным массивом на сутки, а не отдельными
-- строками: 24 строки на день на каждую точку — это в 24 раза больше записей
-- ради данных, которые всегда читаются целиком.
--
--   {"t": [24 температуры], "a": [ощущается как], "p": [осадки, мм],
--    "s": [снег, см], "w": [ветер], "c": [код погоды]}
--
-- Индекс массива — локальный час, 0..23. Пропуск в ряду хранится как null:
-- отсутствие данных и «ноль осадков» это разные вещи.

alter table public.store_kpi_weather
  add column if not exists hourly jsonb null;

comment on column public.store_kpi_weather.hourly is
  'Почасовой ряд на сутки: {"t","a","p","s","w","c"} по 24 значения, индекс = локальный час. Нужен, чтобы считать погоду в окне конкретной смены, а не за сутки целиком.';
