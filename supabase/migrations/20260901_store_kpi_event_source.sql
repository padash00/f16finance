-- ─────────────────────────────────────────────────────────────────────────
-- События смены: откуда взялось — завёл человек или нашла система.
-- ─────────────────────────────────────────────────────────────────────────
-- Отсутствие товара на витрине отмечали руками, а значит почти никогда:
-- вспомнить об этом в конце смены некому. Теперь ходовые позиции с нулевым
-- остатком находит крон и заводит событие сам.
--
-- Отличать автоматические события от ручных обязательно, и вот почему.
-- Крон продлевает и закрывает только свои события: если он начнёт править
-- запись, которую владелец завёл руками, тот однажды обнаружит, что его
-- пометка исчезла, и перестанет доверять журналу целиком.
--
-- На оценку продавца это по-прежнему не влияет: событие снижает уверенность
-- в выводе и попадает в разбор смены, но балл не трогает. Продавец не может
-- продать то, чего нет на витрине, но и заслуги в этом у него нет.

alter table public.store_kpi_business_events
  add column if not exists source text not null default 'manual'
    check (source in ('manual', 'auto'));

comment on column public.store_kpi_business_events.source is
  'manual — завёл человек, auto — нашла система. Крон правит только свои записи.';

-- Открытое авто-событие ищется на каждом прогоне: без индекса это полный скан
-- журнала событий по всем точкам.
create index if not exists idx_store_kpi_business_events_auto
  on public.store_kpi_business_events (company_id, event_type, ends_on desc)
  where source = 'auto';
