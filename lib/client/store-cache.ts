'use client'

import { invalidateApiCache } from '@/lib/client/use-api-cache'

/**
 * Сбросить кэш экранов магазина.
 *
 * Зачем: страницы раздела кэшируют ответы на пять минут, а операции связаны
 * между собой — приёмка меняет остатки склада, ревизия меняет и склад, и
 * витрину, выдача по заявке трогает обе локации. Без сброса соседний экран
 * несколько минут показывал бы цифры до операции.
 *
 * Гасим весь префикс, а не точечно: перечислять зависимости руками — это список,
 * который забудут дополнить при следующей операции, и расхождение всплывёт
 * у клиента, а не в тесте. Кэш живёт в памяти вкладки, сброс ничего не стоит.
 */
export function invalidateStoreCaches() {
  invalidateApiCache('/api/admin/store/')
  invalidateApiCache('/api/admin/inventory/')
}
