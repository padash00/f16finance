/**
 * Привести количество к складскому виду: три знака после запятой.
 *
 * Запятая как десятичный разделитель принимается наравне с точкой — на русской
 * раскладке её набирают чаще, а `Number('1,5')` даёт NaN и молча превращает
 * полтора килограмма в ноль.
 *
 * Округление через EPSILON: без него 0.1 + 0.2 сохраняется как 0.30000000000000004
 * и остаток начинает расходиться с тем, что видит человек.
 */
export function normalizeQty(value: unknown): number {
  const amount = Number(String(value ?? 0).replace(',', '.'))
  if (!Number.isFinite(amount)) return 0
  return Math.round((amount + Number.EPSILON) * 1000) / 1000
}
