/**
 * Пороги наблюдения за станциями — одно место на всю систему.
 *
 * Числа вроде 90 и 30 расползаются по компонентам и роутам за неделю, после
 * чего экран начинает считать станцию офлайн раньше или позже, чем API. Здесь
 * они лежат один раз, и менять их нужно один раз.
 */

/** Как часто устройство подтверждает, что живо и что оно наблюдает. */
export const HEARTBEAT_INTERVAL_SEC = 30

/**
 * Сколько молчания достаточно, чтобы считать станцию офлайн.
 *
 * Три пропущенных подряд. Меньше — ложные срабатывания на любом сетевом
 * заикании, больше — экран будет показывать выключенный компьютер живым
 * несколько минут.
 *
 * Значение подобрано умозрительно и подлежит проверке на реальной сети клуба.
 */
export const OFFLINE_AFTER_SEC = 90

/**
 * Насколько далеко в будущее допустимо время события.
 *
 * У клиента могут врать часы. Событие «из будущего» не должно попадать в
 * проекцию: оно заблокировало бы все последующие наблюдения, и снимок замер бы
 * навсегда. В журнал такое событие всё равно ложится — как улика о расхождении
 * часов, а не как факт о станции.
 */
export const CLOCK_SKEW_FUTURE_TOLERANCE_SEC = 300

/**
 * Насколько глубоко в прошлое принимаем события.
 *
 * Устройство после долгого отсутствия сети может дослать накопленное. Неделя —
 * запас с большим избытком; всё, что старше, скорее говорит о сбитых часах,
 * чем о реальном событии.
 */
export const EVENT_MAX_AGE_SEC = 7 * 24 * 60 * 60

/** Сколько событий принимаем за один запрос. */
export const EVENTS_BATCH_LIMIT = 200

/** Версия правил вывода состояния. Меняется вместе с самими правилами. */
export const ARENA_STATE_VERSION = 'ARENA_STATE_V1'

/** Версия протокола обмена с устройством. */
export const ARENA_PROTOCOL_VERSION = 1

/** Версия схемы событий, которую понимает сервер. */
export const ARENA_SCHEMA_VERSION = 1
