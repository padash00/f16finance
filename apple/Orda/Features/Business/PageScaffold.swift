import OrdaKit
import OrdaUI
import SwiftUI

/// Раздел портала, для которого ещё нет нативного экрана.
///
/// Раньше здесь показывался список прав пользователя и плашка «экран данных
/// подключается позже». Это было честно по форме и бесполезно по сути: на
/// сайте человек этим разделом пользуется, а в приложении упирался в
/// перечень кодов вида `income.create`.
///
/// Теперь открывается настоящая страница портала с той же сессией. Функция
/// доступна сразу, а нативные экраны заменяют веб по одному.
struct PageScaffold: View {
    let page: CapabilityPage
    let resolver: AccessResolver

    var body: some View {
        WebPageView(title: page.label, path: page.path)
    }
}
