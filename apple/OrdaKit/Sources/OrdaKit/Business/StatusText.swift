import Foundation

/// Состояния по-русски.
///
/// Каждая модель переводит свои состояния сама — и правильно делает: «open» у
/// заявки и у долга значит разное. Но у всех переводов был общий запасной
/// выход: если состояние незнакомое, показать его как есть. На экране от этого
/// появлялось слово из базы — например, заголовок «finished» на карточке
/// экзамена.
///
/// Это не мелочь. Незнакомое состояние приходит именно тогда, когда на сервере
/// добавили новое, а приложение ещё старое, — то есть в самый неудачный
/// момент, и человек видит служебный словарь вместо ответа.
///
/// Здесь общий словарь на этот случай. Чего нет и в нём — пусто: пустая
/// подпись честнее английской.
public enum StatusText {

    private static let dictionary: [String: String] = [
        // Общие
        "active": "Активен",
        "inactive": "Отключён",
        "archived": "В архиве",
        "suspended": "Заморожен",
        "draft": "Черновик",
        "new": "Новый",
        "pending": "Ждёт",
        "in_progress": "В работе",
        "completed": "Завершён",
        "finished": "Завершён",
        "done": "Готово",
        "closed": "Закрыт",
        "open": "Открыт",
        "cancelled": "Отменён",
        "canceled": "Отменён",
        "expired": "Просрочен",
        "failed": "Не выполнен",
        "skipped": "Пропущен",
        "partial": "Частично",

        // Решения
        "approved": "Одобрен",
        "confirmed": "Подтверждён",
        "rejected": "Отклонён",
        "declined": "Отклонён",
        "dismissed": "Отклонён",
        "resolved": "Решено",
        "awaiting_reason": "Ждёт причины",

        // Деньги
        "paid": "Оплачен",
        "unpaid": "Не оплачен",
        "written_off": "Списан",
        "past_due": "Просрочен",
        "trialing": "Пробный период",
        "refunded": "Возвращён",

        // Движение товара и документов
        "sent": "Отправлен",
        "received": "Получен",
        "fulfilled": "Выполнен",
        "undeliverable": "Не доставлен",
    ]

    /// Русская подпись состояния. Пусто — состояние неизвестно, и показывать
    /// его нечем: английское слово из базы человеку ничего не объясняет.
    public static func humanize(_ status: String) -> String {
        dictionary[status.lowercased()] ?? ""
    }
}
