/** Врезка правила. Цвет кодирует, что будет, если правило нарушить. */
function Callout({
  kind,
  title,
  children,
}: {
  kind: 'rule' | 'warn' | 'crit'
  title: string
  children: React.ReactNode
}) {
  const styles = {
    rule: 'border-[#16a34a]/30 bg-[#16a34a]/[0.06] text-[#15803d]',
    warn: 'border-[#d97706]/30 bg-[#d97706]/[0.07] text-[#b45309]',
    crit: 'border-[#dc2626]/30 bg-[#dc2626]/[0.06] text-[#b91c1c]',
  }[kind]
  return (
    <div className={`mt-4 rounded-2xl border px-4 py-3.5 ${styles}`}>
      <div className="text-[11px] font-semibold uppercase tracking-wider">{title}</div>
      <div className="mt-1.5 text-sm leading-7 text-[#475569]">{children}</div>
    </div>
  )
}

function Table({ head, rows }: { head: string[]; rows: (string | React.ReactNode)[][] }) {
  return (
    <div className="mt-4 overflow-x-auto">
      <table className="w-full border-collapse text-sm">
        <thead>
          <tr className="border-b border-[#e2e8f0] text-left text-[#0f2038]">
            {head.map((h) => (
              <th key={h} className="py-2 pr-4 font-semibold">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className="border-b border-[#eef2f8] align-top">
              {row.map((cell, j) => (
                <td key={j} className="py-2 pr-4">
                  {cell}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

