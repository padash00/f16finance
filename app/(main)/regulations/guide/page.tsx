/** Название кнопки или поля ровно так, как оно подписано в интерфейсе. */
function Ui({ children }: { children: React.ReactNode }) {
  return (
    <span className="rounded-md bg-slate-100 px-1.5 py-0.5 text-[13px] font-medium text-slate-900 dark:bg-white/10 dark:text-slate-100">
      {children}
    </span>
  )
}

function Section({
  id,
  icon,
  title,
  lead,
  children,
}: {
  id: string
  icon: React.ReactNode
  title: string
  lead?: string
  children: React.ReactNode
}) {
  return (
    <Card id={id} className="p-5">
      <div className="flex items-center gap-2.5">
        <span className="grid h-8 w-8 shrink-0 place-items-center rounded-xl bg-emerald-500/10 text-emerald-600 dark:text-emerald-300">
          {icon}
        </span>
        <h2 className="text-lg font-semibold text-foreground">{title}</h2>
      </div>
      {lead ? <p className="mt-2 text-sm leading-6 text-muted-foreground">{lead}</p> : null}
      <div className="mt-4 space-y-4 text-sm leading-6 text-body">{children}</div>
    </Card>
  )
}

function Steps({ items }: { items: React.ReactNode[] }) {
  return (
    <ol className="space-y-2">
      {items.map((item, index) => (
        <li key={index} className="flex gap-3">
          <span className="mt-0.5 grid h-5 w-5 shrink-0 place-items-center rounded-md bg-slate-900 text-[11px] font-bold text-white dark:bg-white dark:text-slate-900">
            {index + 1}
          </span>
          <span className="min-w-0">{item}</span>
        </li>
      ))}
    </ol>
  )
}

function Table({ head, rows }: { head: string[]; rows: React.ReactNode[][] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full border-collapse text-sm">
        <thead>
          <tr className="border-b border-border text-left text-foreground">
            {head.map((h) => (
              <th key={h} className="py-2 pr-4 font-semibold">{h}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className="border-b border-border/60 align-top">
              {row.map((cell, j) => (
                <td key={j} className="py-2 pr-4">{cell}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}

function Tip({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div className="rounded-2xl border border-amber-400/30 bg-amber-400/[0.08] px-4 py-3">
      <div className="text-[11px] font-semibold uppercase tracking-wider text-amber-700 dark:text-amber-300">{title}</div>
      <div className="mt-1.5 text-sm leading-6 text-body">{children}</div>
    </div>
  )
}

